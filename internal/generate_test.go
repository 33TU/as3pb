func TestGenerateFileMessageFieldsAndReset(t *testing.T) {
	plugin := messagePlugin(t)
	generator := internal.NewGenerator(plugin, internal.Options{})

	if err := generator.GenerateFile(plugin.Files[0]); err != nil {
		t.Fatalf("GenerateFile() error = %v", err)
	}

	files := plugin.Response().GetFile()
	if len(files) != 1 {
		t.Fatalf("generated %d files, want 1", len(files))
	}
	if got, want := files[0].GetName(), "test/v1/Player.as"; got != want {
		t.Fatalf("generated file name = %q, want %q", got, want)
	}

	content := files[0].GetContent()
	wantParts := []string{
		"import flash.utils.ByteArray;",
		"import as3pb.proto.Deserialize;",
		"import as3pb.proto.Serialize;",
		"import as3pb.proto.Buffers;",
		"import as3pb.types.Int64;",
		"import as3pb.types.AnyRegistry;",
		`public static const TYPE_URL:String = "type.googleapis.com/test.v1.Player";`,
		"public static const FIELD_MOVE:uint = 5;",
		"public var raw:ByteArray = Buffers.newByteArray();",
		"public static function reset(msg:Player):void",
		"msg.raw.length = 0;",
		"public static function deserializeBytes(src:ByteArray, dst:Player = null, limit:uint = 0):Player",
		"else",
		"dst.actionCase = 5;",
		"Deserialize.readInt32Vector(src, dst.scores);",
		"public static function serializeBytes(src:Player, dst:ByteArray):void",
		"const reuseBuffer:ByteArray = Buffers.SHARED_BUFFER;",
		"Serialize.writeInt32Vector(dst, localScores, reuseBuffer, vecLength);",
		"switch (src.actionCase)",
		"AnyRegistry.register(TYPE_URL, deserializeBytes, serializeBytes);",
	}
	for _, want := range wantParts {
		if !strings.Contains(content, want) {
			t.Fatalf("generated content missing %q:\n%s", want, content)
		}
	}
}

