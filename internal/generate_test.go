func TestGenerateFileEnum(t *testing.T) {
	plugin := enumPlugin(t, true)
	generator := internal.NewGenerator(plugin, internal.Options{})

	if err := generator.GenerateFile(plugin.Files[0]); err != nil {
		t.Fatalf("GenerateFile() error = %v", err)
	}

	files := plugin.Response().GetFile()
	if len(files) != 1 {
		t.Fatalf("generated %d files, want 1", len(files))
	}
	if got, want := files[0].GetName(), "test/v1/PlayerStatus.as"; got != want {
		t.Fatalf("generated file name = %q, want %q", got, want)
	}

	want := `/**
 * Code generated by protoc-gen-as3.
 * Source: test.proto
 */
package test.v1
{
    public final class PlayerStatus
    {
        public static const PLAYER_STATUS_UNKNOWN:uint = 0;
        public static const PLAYER_STATUS_ACTIVE:uint = 1;
    }
}
`
	if got := files[0].GetContent(); got != want {
		t.Fatalf("generated content:\n%s\nwant:\n%s", got, want)
	}
}

